"""Regenerate quartz.config.yaml from Quartz's own default at the pinned commit, with this site's changes applied.

    python scripts/make_quartz_config.py path/to/quartz-checkout

Keeping the config as "Quartz default + a short list of changes" makes Quartz upgrades a re-run, not a merge.
The result is checked against Quartz's JSON Schema (patched for two places where the schema lags Quartz's own types:
layout positions "header"/"footer", and typography "title").
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import jsonschema
import yaml

ROOT = Path(__file__).resolve().parents[1]
OFF = {
    "@quartz-community/graph",              # replaced by the Sigma explorer at /graph/
    "@quartz-community/note-properties",    # replaced by the provenance callout kfsite writes
    "@quartz-community/latex", "@quartz-community/syntax-highlighting", "@quartz-community/og-image",
    "@quartz-community/cname", "@quartz-community/canvas-page", "@quartz-community/bases-page",
    "@quartz-community/encrypted-pages", "@quartz-community/comments", "@quartz-community/stacked-pages",
    "@quartz-community/recent-notes", "@quartz-community/explicit-publish",
}
ON = {"@quartz-community/tag-list"}
OPTIONS = {
    "@quartz-community/created-modified-date": {"defaultDateType": "modified", "priority": ["frontmatter", "filesystem"]},
    "@quartz-community/crawl-links": {"markdownLinkResolution": "absolute"},
    "@quartz-community/obsidian-flavored-markdown": {"enableInHtmlEmbed": False, "enableCheckbox": False},
    "@quartz-community/footer": {"links": {
        "Essays (muthub.org)": "https://muthub.org", "Graph explorer": "https://wiki.muthub.org/graph/",
        "llms.txt": "https://wiki.muthub.org/llms.txt", "Source": "https://github.com/muthub-ai/knowledge-foundation",
        "LinkedIn": "https://www.linkedin.com/in/mbommiah/"}},
}
THEME = {
    "fontOrigin": "googleFonts", "cdnCaching": True,
    "typography": {"header": "Newsreader", "body": "Instrument Sans", "code": "IBM Plex Mono"},
    "colors": {  # muthub.org's tokens
        "lightMode": {"light": "#ffffff", "lightgray": "#e7e5e0", "gray": "#cfccc5", "darkgray": "#3f4450", "dark": "#15171c",
                      "secondary": "#0b5c6b", "tertiary": "#3d8794", "highlight": "rgba(11, 92, 107, 0.08)", "textHighlight": "#fff23688"},
        "darkMode": {"light": "#0f1114", "lightgray": "#2a2d33", "gray": "#464a52", "darkgray": "#c3c6cc", "dark": "#ededea",
                     "secondary": "#6ec4d2", "tertiary": "#9fd6df", "highlight": "rgba(110, 196, 210, 0.12)", "textHighlight": "#b3aa0288"},
    },
}
HEADER = """# Quartz 5 configuration for wiki.muthub.org. Generated by scripts/make_quartz_config.py from Quartz's own default
# (quartz.config.default.yaml at the commit in quartz.ref); edit that script, not this file.
# yaml-language-server: $schema=./quartz/plugins/quartz-plugins.schema.json
"""


def make(quartz: Path) -> dict:
    cfg = yaml.safe_load((quartz / "quartz.config.default.yaml").read_text(encoding="utf-8"))
    cfg["configuration"].update({
        "pageTitle": "Knowledge Foundation", "pageTitleSuffix": " · Knowledge Foundation", "enableSPA": True, "enablePopovers": True,
        "analytics": None, "locale": "en-US", "baseUrl": "wiki.muthub.org", "theme": THEME,
    })
    for p in cfg["plugins"]:
        s = p["source"]
        if s in OFF:
            p["enabled"] = False
        if s in ON:
            p["enabled"] = True
        if s in OPTIONS:
            p["options"] = OPTIONS[s]
    missing = (OFF | ON | set(OPTIONS)) - {p["source"] for p in cfg["plugins"]}
    if missing:
        raise SystemExit(f"Quartz's default no longer lists: {', '.join(sorted(missing))}")
    schema = json.loads((quartz / "quartz/plugins/quartz-plugins.schema.json").read_text(encoding="utf-8"))
    pos = schema["properties"]["plugins"]["items"]["properties"]["layout"]["properties"]["position"]
    pos["enum"] = sorted(set(pos["enum"]) | {"header", "footer"})
    jsonschema.validate(cfg, schema)
    return cfg


if __name__ == "__main__":
    cfg = make(Path(sys.argv[1]))
    (ROOT / "quartz.config.yaml").write_text(HEADER + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
    print("quartz.config.yaml:", sum(p["enabled"] for p in cfg["plugins"]), "plugins enabled, valid against Quartz's schema")
